"""Microsoft Graph Intune adapter. Submission is never execution success.

The caller must persist operations, enforce tenant ownership, approval and one
active operation per device/policy before calling submit. Credentials belong to
the configured Microsoft tenant, not to a plan generated by an LLM.
"""
from dataclasses import dataclass
from datetime import datetime, timezone
import json
import re
from urllib.parse import urlsplit
import urllib.error
import urllib.request


class RemoteError(RuntimeError):
    pass


class NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        return None


def request_json(method, url, *, headers=None, data=None):
    """Bounded HTTPS request with redirects disabled and no error-body logging."""
    req = urllib.request.Request(url, method=method, headers=headers or {}, data=data)
    opener = urllib.request.build_opener(urllib.request.ProxyHandler({}), NoRedirect())
    try:
        with opener.open(req, timeout=30) as response:
            raw = response.read(2_000_001)
            if len(raw) > 2_000_000:
                raise RemoteError("Remote response exceeds size limit")
            return response.status, json.loads(raw) if raw else None
    except urllib.error.HTTPError as exc:
        raise RemoteError(f"Remote HTTP {exc.code}") from None
    except (urllib.error.URLError, ValueError):
        raise RemoteError("Remote response unavailable or invalid") from None


def identifier(value):
    if not isinstance(value, str) or not re.fullmatch(r"[a-zA-Z0-9_-]{1,128}", value):
        raise ValueError("Invalid device, policy or tenant identifier")
    return value


def timestamp(value):
    if not isinstance(value, str):
        return None
    try:
        parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
        return parsed.astimezone(timezone.utc) if parsed.tzinfo else None
    except ValueError:
        return None


@dataclass(frozen=True)
class IntuneOperation:
    microsoft_tenant_id: str
    device_id: str
    policy_id: str
    submitted_at: str

    def as_dict(self):
        return vars(self).copy()


class IntuneClient:
    GRAPH = "https://graph.microsoft.com"

    def __init__(self, microsoft_tenant_id, access_token, *, transport=request_json):
        self.microsoft_tenant_id = identifier(microsoft_tenant_id)
        if not access_token:
            raise ValueError("Graph access token is required")
        self._access_token, self.transport = access_token, transport

    @classmethod
    def from_client_credentials(cls, tenant_id, client_id, client_secret, *, transport=request_json):
        from urllib.parse import urlencode
        tenant_id = identifier(tenant_id)
        if not client_id or not client_secret:
            raise ValueError("Microsoft application credentials are required")
        code, body = transport("POST", f"https://login.microsoftonline.com/{tenant_id}/oauth2/v2.0/token",
                               headers={"Content-Type": "application/x-www-form-urlencoded"},
                               data=urlencode({"client_id": client_id, "client_secret": client_secret,
                                               "scope": cls.GRAPH + "/.default",
                                               "grant_type": "client_credentials"}).encode())
        if code != 200 or not isinstance(body, dict) or not body.get("access_token"):
            raise RemoteError("Microsoft authentication failed")
        return cls(tenant_id, body["access_token"], transport=transport)

    def _request(self, method, path, payload=None):
        # nextLink is remote input; never send a bearer token to another origin.
        url = self.GRAPH + path if path.startswith("/") else path
        parts = urlsplit(url)
        if parts.scheme != "https" or parts.netloc != "graph.microsoft.com" or not parts.path.startswith(("/v1.0/", "/beta/")):
            raise RemoteError("Graph URL outside configured origin")
        return self.transport(method, url,
                              headers={"Authorization": "Bearer " + self._access_token,
                                       "Content-Type": "application/json"},
                              data=json.dumps(payload).encode() if payload is not None else None)

    def _collection(self, path):
        values, seen = [], set()
        for _ in range(20):
            if path in seen:
                raise RemoteError("Repeated Graph pagination link")
            seen.add(path)
            code, body = self._request("GET", path)
            if code != 200 or not isinstance(body, dict) or not isinstance(body.get("value"), list):
                raise RemoteError("Invalid Graph collection")
            values.extend(body["value"])
            path = body.get("@odata.nextLink")
            if not path:
                return values
        raise RemoteError("Graph pagination limit exceeded")

    def list_devices(self):
        return self._collection("/v1.0/deviceManagement/managedDevices?$select=id,deviceName,operatingSystem,lastSyncDateTime,azureADDeviceId")

    def list_policies(self):
        return self._collection("/beta/deviceManagement/deviceHealthScripts?$select=id,displayName,version")

    def submit(self, device_id, policy_id):
        """Launch a pre-provisioned policy; never uploads arbitrary LLM scripts."""
        device_id, policy_id = identifier(device_id), identifier(policy_id)
        submitted = datetime.now(timezone.utc).isoformat()
        code, _ = self._request("POST", f"/beta/deviceManagement/managedDevices/{device_id}/initiateOnDemandProactiveRemediation",
                                {"scriptPolicyId": policy_id})
        if code != 204:
            raise RemoteError("Intune did not accept the remediation")
        return IntuneOperation(self.microsoft_tenant_id, device_id, policy_id, submitted)

    def poll(self, operation):
        if operation.microsoft_tenant_id != self.microsoft_tenant_id:
            raise RemoteError("Operation belongs to a different Microsoft tenant")
        device, policy = identifier(operation.device_id), identifier(operation.policy_id)
        submitted = timestamp(operation.submitted_at)
        if not submitted:
            raise ValueError("Operation requires an aware submission timestamp")
        states = self._collection(f"/beta/deviceManagement/deviceHealthScripts/{policy}/deviceRunStates?$expand=managedDevice")
        matches = [s for s in states if (s.get("managedDevice") or {}).get("id") == device
                   and timestamp(s.get("lastStateUpdateDateTime"))
                   and timestamp(s["lastStateUpdateDateTime"]) >= submitted]
        if not matches:
            return {"status": "PENDING", "reason": "No fresh device result", "operation": operation.as_dict()}
        state = max(matches, key=lambda s: timestamp(s["lastStateUpdateDateTime"]))
        errors = [state.get(k) for k in ("remediationScriptError", "postRemediationDetectionScriptError") if state.get(k)]
        result = "PENDING"
        if state.get("remediationState") in ("remediationFailed", "scriptError") or errors:
            result = "FAILED"
        elif state.get("remediationState") == "success" and state.get("detectionState") == "success":
            result = "SUCCEEDED"
        elif state.get("remediationState") == "skipped" and state.get("detectionState") == "success":
            result = "NO_CHANGE_NEEDED"
        return {"status": result, "operation": operation.as_dict(), "device_result": state}
